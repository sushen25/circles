/**
 * `npm run brief`: context/learned.md from analytics/scorecard.json
 * (docs/analytics-plan.md, "Brief and drafting"). Short on purpose, under
 * sixty lines, dated, every line carrying its n, regenerated nightly and
 * never edited by hand. It says what worked; it never names a fact, so it
 * can never add a claim (`/review` fails a queue file that cites it as a
 * source). /hooks and /skit read it after voice.md, facts.md and hooks.md,
 * and none of those three is overridden by it.
 *
 * Only what the scorecard ranked reaches "Do more of" and "Stop": a group
 * with n at MIN_N or more whose median lift is at least LEAD or at most LAG,
 * and a feature split whose gap is wider than the spread within its sides.
 * Everything under MIN_N is "Too early", which the skills read as no
 * information.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { MIN_N } from './aggregates.ts';
import type { Scorecard } from './scorecard.ts';

/** A median lift at or above this is worth doing more of; at or below LAG, worth stopping. */
export const LEAD = 1.2;
export const LAG = 0.8;
/** The brief's hard ceiling. */
export const MAX_LINES = 60;
const PER_SECTION = 8;

const num = (v: number | null) => (v === null ? '–' : String(Math.round(v * 100) / 100));

export function renderBrief(c: Scorecard): string {
  const more: string[] = [];
  const stop: string[] = [];
  const content = c.groups.filter((g) => g.ranked && g.median_lift !== null && g.dimension !== 'hour' && g.dimension !== 'weekday');
  for (const g of content) {
    const per = Object.entries(g.by_platform)
      .filter(([, v]) => v!.ranked)
      .map(([p, v]) => `${p} ${num(v!.median_lift)}`)
      .join(', ');
    const line = `- ${g.value} ${g.dimension}: lift ${num(g.median_lift)} (n=${g.n}, day 7)${per ? `; ${per}` : ''}`;
    if (g.median_lift! >= LEAD) more.push(line);
    else if (g.median_lift! <= LAG) stop.push(line);
  }
  for (const s of c.splits.filter((x) => x.reportable)) {
    const yesWins = (s.yes.median_lift ?? 0) > (s.no.median_lift ?? 0);
    const line = `- ${s.name}: lift ${num(s.yes.median_lift)} against ${num(s.no.median_lift)} without (n=${s.yes.n} vs ${s.no.n})`;
    (yesWins ? more : stop).push(line);
  }
  if (c.control?.ranked) {
    const { story_first: st, demo_first: d } = c.control;
    const line = `- demo-first against story-first (the control arm): lift ${num(d.median_lift)} against ${num(st.median_lift)} (n=${d.n} vs ${st.n})`;
    ((d.median_lift ?? 0) > (st.median_lift ?? 0) ? more : stop).push(line);
  }

  const windows: string[] = [];
  for (const [platform, m] of Object.entries(c.medians)) {
    const hours = c.groups
      .filter((g) => g.dimension === 'hour' && g.by_platform[platform as keyof typeof g.by_platform]?.ranked)
      .map((g) => ({ value: g.value, ...g.by_platform[platform as keyof typeof g.by_platform]! }))
      .sort((a, b) => (b.median_lift ?? 0) - (a.median_lift ?? 0));
    if (!hours.length) windows.push(`- ${platform}: too early, no hour has ${MIN_N} pieces (n=${m!.n})`);
    else if ((hours[0].median_lift ?? 0) >= LEAD) windows.push(`- ${platform}: ${hours[0].value} Melbourne posts lead, lift ${num(hours[0].median_lift)} (n=${hours[0].n})`);
    else windows.push(`- ${platform}: no difference seen across ${hours.length} hour${hours.length === 1 ? '' : 's'} (n=${hours.reduce((a, h) => a + h.n, 0)})`);
  }

  const quoted = new Map<string, number>();
  for (const p of c.pieces) if (p.hook_quotes) quoted.set(p.slug, (quoted.get(p.slug) ?? 0) + p.hook_quotes);
  const replies = [...quoted].sort((a, b) => b[1] - a[1]).map(([slug, n]) => `- ${slug}: its hook quoted back in replies (n=${n})`);

  const early = c.too_early.length ? [`- ${c.too_early.slice(0, 24).join('; ')}${c.too_early.length > 24 ? `; and ${c.too_early.length - 24} more` : ''}`] : [];

  const section = (title: string, lines: string[], empty: string) => [`## ${title}`, ...(lines.length ? lines.slice(0, PER_SECTION) : [empty]), ''];
  const out = [
    '# Learned',
    '',
    `Generated by npm run brief on ${c.day} from analytics/scorecard.json.`,
    'Never edit by hand; the next nightly run overwrites it. Lift is against the platform median at day 7.',
    '',
    ...section('Do more of', more, `- nothing yet: no group has ${MIN_N} pieces and a lift of ${LEAD} or more`),
    ...section('Stop', stop, `- nothing yet: no group has ${MIN_N} pieces and a lift of ${LAG} or less`),
    ...section('Too early', early, '- nothing listed'),
    ...section('Windows', windows, '- too early: no piece is seven days old'),
    ...section('Replies', replies, '- no reply has quoted a hook back yet (n=0)'),
  ];
  return out.slice(0, MAX_LINES).join('\n').trimEnd() + '\n';
}

function main(): void {
  const card = JSON.parse(readFileSync('analytics/scorecard.json', 'utf8')) as Scorecard;
  writeFileSync('context/learned.md', renderBrief(card));
  console.log('brief → context/learned.md');
}

const entry = process.argv[1] ? resolve(process.argv[1]) : '';
if (entry && fileURLToPath(import.meta.url) === entry) main();
