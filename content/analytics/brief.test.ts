import { test } from 'node:test';
import assert from 'node:assert/strict';
import { MAX_LINES, renderBrief } from './brief.ts';
import { buildScorecard, type Scorecard } from './scorecard.ts';
import { NOW, inputs } from './scorecard.fixture.ts';

const brief = () => renderBrief(buildScorecard(inputs(), NOW));

test('the brief is dated, under sixty lines, and every finding carries its n', () => {
  const md = brief();
  assert.match(md, /^# Learned\n\nGenerated by npm run brief on 2026-11-18/);
  assert.ok(md.split('\n').length <= MAX_LINES);
  for (const line of md.split('\n').filter((l) => l.startsWith('- ') && !l.startsWith('- nothing'))) assert.match(line, /n=\d/, line);
});

test('only what was ranked is in Do more of and Stop', () => {
  const md = brief();
  const more = md.split('## Do more of\n')[1].split('\n\n')[0];
  const stop = md.split('## Stop\n')[1].split('\n\n')[0];
  assert.match(more, /- pm family: lift [\d.]+ \(n=3, day 7\)/);
  assert.match(more, /- hook with a number: lift [\d.]+ against [\d.]+ without \(n=3 vs 3\)/);
  assert.match(stop, /- 20:00–21:00 hour|- caption ends in a question|nothing yet/);
  assert.doesNotMatch(more + stop, /skit family|rhythm family|like/);
  assert.match(md, /## Too early\n- .*family skit \(n=2\)/);
});

test('windows say which hour leads on each platform, or that it is too early', () => {
  const md = brief();
  assert.match(md, /- instagram: 18:00–19:00 Melbourne posts lead, lift [\d.]+ \(n=3\)/);
  assert.match(md, /- tiktok: too early/);
});

test('replies that quote a hook back are counted by piece', () => {
  assert.match(brief(), /- pm-one: its hook quoted back in replies \(n=1\)/);
});

test('with nothing ranked the brief says so rather than guessing', () => {
  const md = renderBrief(buildScorecard({ ...inputs(), posts: [], hand: [], series: [] }, NOW));
  assert.match(md, /## Do more of\n- nothing yet/);
  assert.match(md, /## Windows\n- too early/);
});

const split = (yes: number, no: number): Scorecard => ({
  ...buildScorecard({ ...inputs(), posts: [], hand: [], series: [] }, NOW),
  splits: [{ name: 'hook with a number', yes: { label: 'yes', n: 3, median_lift: yes }, no: { label: 'no', n: 3, median_lift: no }, spread: 0, reportable: true }],
});

test('a reportable split still has to clear the lead or lag bar to be advice', () => {
  assert.doesNotMatch(renderBrief(split(1.05, 1)), /hook with a number/);
  assert.match(renderBrief(split(1.3, 0.9)).split('## Stop')[0], /- hook with a number: lift 1\.3 against 0\.9 without/);
  assert.match(renderBrief(split(0.7, 1.1)).split('## Stop')[1].split('## Too early')[0], /- hook with a number: lift 0\.7/);
  // "without" leading is advice too: doing it is the thing to stop
  assert.match(renderBrief(split(1, 1.6)).split('## Stop')[1].split('## Too early')[0], /- hook with a number: lift 1 against 1\.6 without/);
});

test('one ranked hour on a platform is nothing to compare, not a lead', () => {
  const c = buildScorecard(inputs(), NOW);
  c.groups = c.groups.filter((g) => !(g.dimension === 'hour' && g.value.startsWith('20')));
  assert.match(renderBrief(c), /- instagram: only 18:00–19:00 has 3 pieces, nothing to compare it with \(n=3\)/);
});
