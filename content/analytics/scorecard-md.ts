/**
 * analytics/scorecard.md, the dashboard (there is no other): the same
 * numbers as scorecard.json, laid out to be read in two minutes. Ranked
 * things first, then the pieces, then context. Every aggregate shows its n;
 * the like rate is listed beside a piece and ranked nowhere.
 */
import { UNRANKED } from './metrics.ts';
import { MIN_N, type Side } from './aggregates.ts';
import type { PieceScore, Scorecard } from './scorecard.ts';

const num = (v: number | null | undefined, places = 2) => (v === null || v === undefined || Number.isNaN(v) ? '–' : String(Math.round(v * 10 ** places) / 10 ** places));
const sideCell = (s: Side) => `${num(s.median_lift)} (n=${s.n})`;
const RATE_NAME: Record<string, string> = {
  saves_shares_per_k: 'saves+shares /1k views',
  comments_per_k: 'comments /1k views',
  engagement: 'replies+reposts+quotes per post',
};

function ageCell(p: PieceScore, age: string): string {
  const s = p.ages[age as keyof PieceScore['ages']];
  if (!s) return '–';
  const v = s.rates[p.headline];
  return `${num(v)}${s.source === 'pull' ? '' : '†'}`;
}

function latestCell(p: PieceScore): string {
  const s = p.latest;
  if (!s) return '–';
  return `${num(s.rates[p.headline])}${s.source === 'pull' ? '' : '†'} at ${num(s.age_days, 1)} d`;
}

/** Watch percentage (average watch over the measured length) and skip rate, where the platform gives them. */
function watchCell(p: PieceScore): string {
  const r = p.latest?.rates;
  if (r?.watch_pct === undefined && r?.skip_pct === undefined) return '–';
  return `${r.watch_pct === undefined ? '–' : `${num(r.watch_pct, 1)}%`} / ${r.skip_pct === undefined ? '–' : `${num(r.skip_pct, 1)}%`}`;
}

function likeRate(p: PieceScore): string {
  const like = [...UNRANKED].map((k) => p.latest?.rates[k]).find((v) => v !== undefined);
  return like === undefined ? '–' : `${num(like * 100, 1)}%`;
}

export function renderScorecard(c: Scorecard): string {
  const out: string[] = [];
  const push = (...l: string[]) => out.push(...l);
  push(
    '# Scorecard',
    '',
    `Generated by \`npm run scorecard\` on ${c.day} from \`analytics/*.jsonl\`. Never edit by hand; the next nightly run overwrites it.`,
    '',
    `Lift is a piece's day-7 rate over the median of every piece on the same platform at day 7, so platforms are never pooled, and there is none until a platform has ${MIN_N} pieces at day 7. n counts pieces, each once. Nothing with n under ${MIN_N} is ranked; it is listed under "Too early". The like rate is listed, never ranked. † marks a number typed or read off a screen.`,
    '',
  );

  push('## Day-7 medians', '');
  const medians = Object.entries(c.medians);
  if (!medians.length) push('No piece is seven days old on any platform yet.', '');
  else {
    push('| platform | ranked on | median | n |', '|---|---|---|---|');
    for (const [p, m] of medians) push(`| ${p} | ${RATE_NAME[m!.rate] ?? m!.rate} | ${num(m!.median)} | ${m!.n} |`);
    push('');
  }

  if (c.control) {
    push('## Control arm', '');
    const verdict = c.control.ranked ? '' : ` Too early: each side needs ${MIN_N} pieces.`;
    push(`Story-first shapes ${sideCell(c.control.story_first)} against demo-first ${sideCell(c.control.demo_first)}, median lift.${verdict}`, '');
  }

  const ranked = c.groups.filter((g) => g.ranked);
  push('## Ranked', '');
  if (!ranked.length) push(`Nothing has ${MIN_N} pieces at day 7 yet.`, '');
  else {
    push('| by | value | median lift | n | per platform |', '|---|---|---|---|---|');
    for (const g of ranked) {
      const per = Object.entries(g.by_platform)
        .map(([p, v]) => `${p} ${v!.ranked ? num(v!.median_lift) : '–'} (n=${v!.n})`)
        .join(', ');
      push(`| ${g.dimension} | ${g.value} | ${num(g.median_lift)} | ${g.n} | ${per} |`);
    }
    push('');
  }

  if (c.splits.length) {
    push('## Feature splits', '', '| split | yes | no | reads |', '|---|---|---|---|');
    for (const s of c.splits) {
      const reads = !s.yes.n || !s.no.n
        ? 'no contrast yet'
        : s.yes.n < MIN_N || s.no.n < MIN_N ? 'too early' : s.reportable ? `gap wider than the spread (${num(s.spread)})` : `within the spread (${num(s.spread)})`;
      push(`| ${s.name} | ${sideCell(s.yes)} | ${sideCell(s.no)} | ${reads} |`);
    }
    push('');
  }

  push('## Pieces', '');
  if (!c.pieces.length) push('No published piece has a row yet.', '');
  else {
    push('| piece | platform | ranked on | day 1 | day 3 | day 7 | day 14 | latest | lift | watch / skip | like rate | replies (quote the hook) |', '|---|---|---|---|---|---|---|---|---|---|---|---|');
    for (const p of c.pieces) {
      push(
        `| ${p.slug} | ${p.platform} | ${RATE_NAME[p.headline] ?? p.headline} | ${ageCell(p, '1')} | ${ageCell(p, '3')} | ${ageCell(p, '7')} | ${ageCell(p, '14')} | ${latestCell(p)} | ${num(p.lift)} | ${watchCell(p)} | ${likeRate(p)} | ${p.replies} (${p.hook_quotes}) |`,
      );
    }
    push('');
  }

  const tagged = c.pieces.filter((p) => p.funnel);
  if (tagged.length || c.stalled) {
    push('## After the tap', '', "What Wenna counted on each piece's link tag, from the nightly export: raw counts, never rates, because the numbers are small and a rate would lie. No person is in it.", '');
    if (tagged.length) {
      push('| piece | platform | circles made | plans shared | answered | confirmed | as of |', '|---|---|---|---|---|---|---|');
      for (const p of tagged) push(`| ${p.slug} | ${p.platform} | ${p.funnel!.circles} | ${p.funnel!.plans_shared} | ${p.funnel!.answered} | ${p.funnel!.confirmed} | ${p.funnel!.as_of} |`);
      push('');
    }
    if (c.stalled) {
      const n = c.stalled.groups.reduce((t, g) => t + g.circles, 0);
      push(`First plans from content that stopped, as of ${c.stalled.as_of}: ${n}${n ? ` (${c.stalled.groups.map((g) => `${g.circles} ${g.state.replace(/_/g, ' ')}, oldest ${g.oldest_hours} h`).join('; ')})` : ''}.`, '');
    }
  }

  const young = c.pieces.filter((p) => p.first48);
  if (young.length) {
    push('## First 48 hours', '', '| piece | platform | 2 h | 6 h | 12 h | 24 h | 48 h | bent at |', '|---|---|---|---|---|---|---|---|');
    for (const p of young) {
      const v = p.first48!.views;
      push(`| ${p.slug} | ${p.platform} | ${num(v.h2, 0)} | ${num(v.h6, 0)} | ${num(v.h12, 0)} | ${num(v.h24, 0)} | ${num(v.h48, 0)} | ${p.first48!.bent_at_h === undefined ? '–' : `${p.first48!.bent_at_h} h`} |`);
    }
    push('');
  }

  const screens = c.pieces.flatMap((p) => p.screens.map((s) => ({ p, s })));
  if (screens.length) {
    push('## Screens', '', 'Read off Insights screenshots (`by: transcribed`); the slide is the one on screen at that tenth, from the measured slide seconds.', '');
    for (const { p, s } of screens) {
      const parts: string[] = [];
      if (s.retention) parts.push(`retention ${s.retention.map((r) => `${r.tenth} ${r.pct}%${r.slide ? ` (slide ${r.slide})` : ''}`).join(' · ')}`);
      if (s.sources) parts.push(`sources ${Object.entries(s.sources).map(([k, v]) => `${k.replace(/_/g, ' ')} ${v}%`).join(', ')}`);
      if (parts.length) push(`- ${p.slug} · ${p.platform} · ${s.screen}${s.captured_at ? ` (${s.captured_at.slice(0, 16).replace('T', ' ')})` : ''}: ${parts.join('; ')}`);
    }
    push('');
  }

  if (c.account.length) {
    push('## The account', '', 'Context only: an account number is never put down to one post.', '');
    for (const a of c.account) push(`- ${a.platform}, ${a.date}: ${a.text || 'no numbers'}`);
    push('');
  }

  push('## Too early', '');
  push(c.too_early.length ? c.too_early.map((t) => `- ${t}`).join('\n') : '- nothing listed', '');
  return out.join('\n');
}
