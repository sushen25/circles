// The ADR index (`docs/decisions/index.md`) is generated from each record's
// frontmatter (SUS-228), so adding an ADR never means editing a shared table.
// Shared by `gen-adr-index.mjs` (writes it) and `check-docs.mjs` (fails when
// it is stale).
import { readFileSync, readdirSync } from 'node:fs';
import { join } from 'node:path';

export const DIR = join(process.cwd(), 'docs', 'decisions');
export const INDEX = join(DIR, 'index.md');

// The frontmatter this repository writes: scalars, double-quoted strings and
// `[1, 2]` lists of numbers. Anything richer is a reason to reach for a parser.
export function frontmatter(text) {
  if (!text.startsWith('---\n')) return null;
  const end = text.indexOf('\n---\n', 4);
  if (end < 0) return null;
  const fields = {};
  for (const line of text.slice(4, end).split('\n')) {
    const match = /^([a-z_]+):\s*(.*)$/.exec(line);
    if (!match) continue;
    let value = match[2].trim();
    if (value.startsWith('[') && value.endsWith(']')) {
      value = value
        .slice(1, -1)
        .split(',')
        .map((item) => item.trim())
        .filter(Boolean)
        .map(Number);
    } else if (value.startsWith('"') && value.endsWith('"')) {
      value = JSON.parse(value);
    }
    fields[match[1]] = value;
  }
  return fields;
}

const pad = (n) => String(n).padStart(4, '0');
const list = (numbers) => numbers.map(pad).join(', ');

export function renderIndex() {
  const rows = [];
  for (const name of readdirSync(DIR)
    .filter((n) => /^\d{4}-.*\.md$/.test(n))
    .sort()) {
    const fm = frontmatter(readFileSync(join(DIR, name), 'utf8'));
    if (!fm) throw new Error(`${name}: no frontmatter; start from docs/_templates/adr.md`);
    let status = String(fm.status);
    const notes = [];
    if (Array.isArray(fm.amended_by) && fm.amended_by.length > 0)
      notes.push(`amended by ${list(fm.amended_by)}`);
    if (Array.isArray(fm.amends) && fm.amends.length > 0) notes.push(`amends ${list(fm.amends)}`);
    if (notes.length > 0) status += ` (${notes.join('; ')})`;
    rows.push(`| [${name.slice(0, 4)}](./${name}) | ${fm.title} | ${status} |`);
  }
  return [
    '# ADR index',
    '',
    "<!-- Generated by `pnpm gen:adrs` from each record's frontmatter. Do not edit by hand. -->",
    '',
    'Every decision record, in order. The rules for writing one are in [the README](./README.md).',
    '',
    '| ADR | Decision | Status |',
    '|---|---|---|',
    ...rows,
    '',
  ].join('\n');
}

export const indexRows = (text) => text.split('\n').filter((line) => line.startsWith('| ['));
